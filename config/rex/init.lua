-- Terminal bindings migrated to Rex.
-- ctrl+b: tmux keys. ctrl+a: Herdr keys.

rex.mode("repeat", { exclusive = true })
rex.bind("ctrl+b>ctrl+r", "client.mode.enter", { name = "repeat" })
rex.bind("repeat/enter", "client.mode.exit")
rex.bind("repeat/escape", "client.mode.exit")

rex.mode("resize", { exclusive = true })
rex.bind("resize/enter", "client.mode.exit")
rex.bind("resize/escape", "client.mode.exit")

rex.action{
  name = "alacritty_open_config",
  title = "Open Alacritty Config",
  run = function(ctx, args)
    rex.exec{ "sh", "-c", "open ~/.config/alacritty/alacritty.yml" }
  end
}


